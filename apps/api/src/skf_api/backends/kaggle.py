"""kaggle: runs a train stage as a private Kaggle script kernel on a free GPU.

Kaggle takes one source file, so the kernel embeds the g1pipe bundle, the reporter and the rendered
argv, the same way scripts/kaggle_job.py does (its PINS, BUNDLE and NOISE are imported from that file,
which stays the single source of truth). Warm starts mount the parent kernel's output through
`kernel_sources`. All calls go through the `kaggle` CLI with the key in its environment only.
"""

